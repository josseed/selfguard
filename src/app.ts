/**
 * `selfguard app install`: a tiny macOS app (~/Applications/selfguard.app) that opens the
 * dashboard, so it can be launched from Spotlight, Launchpad or the Dock.
 *
 * The bundle is generated on the user's machine (never downloaded), so Gatekeeper doesn't
 * quarantine it and no Apple signing is needed. Its executable is a two-line shell script
 * that runs this selfguard install with absolute paths. Nothing else.
 */
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { atomicWrite } from "./fsutil.ts";
import { cliEntry } from "./hook.ts";
import { VERSION } from "./version.ts";

const BUNDLE_ID = "dev.selfguard.app";

export const appPath = (): string => join(homedir(), "Applications", "selfguard.app");
const iconSource = (): string => fileURLToPath(new URL("./assets/selfguard.icns", import.meta.url));

/** Quote for /bin/sh: everything inside single quotes is literal. */
export function shQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

function xml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

export function launcherScript(node: string, cli: string): string {
  return `#!/bin/sh\n# Generated by \`selfguard app install\`: opens the selfguard dashboard.\nexec ${shQuote(node)} ${shQuote(cli)} ui\n`;
}

export function infoPlist(): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleExecutable</key><string>selfguard</string>
  <key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
  <key>CFBundleName</key><string>selfguard</string>
  <key>CFBundleDisplayName</key><string>selfguard</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>${xml(VERSION)}</string>
  <key>CFBundleIconFile</key><string>selfguard</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>LSUIElement</key><true/>
  <key>NSHumanReadableCopyright</key><string>MIT License</string>
</dict>
</plist>
`;
}

function assertMac(): void {
  if (process.platform !== "darwin") throw new Error("the launcher app is only available on macOS");
}

export interface AppStatus {
  installed: boolean;
  path: string;
  /** The app points at this selfguard and Node (false after switching Node versions). */
  upToDate: boolean;
}

export function appStatus(): AppStatus {
  const path = appPath();
  const exe = join(path, "Contents", "MacOS", "selfguard");
  let current = "";
  try {
    current = readFileSync(exe, "utf8");
  } catch {
    return { installed: false, path, upToDate: false };
  }
  return { installed: true, path, upToDate: current === launcherScript(process.execPath, cliEntry()) };
}

export function installApp(): AppStatus {
  assertMac();
  const path = appPath();
  rmSync(path, { recursive: true, force: true });
  const contents = join(path, "Contents");
  mkdirSync(join(contents, "MacOS"), { recursive: true });
  mkdirSync(join(contents, "Resources"), { recursive: true });
  atomicWrite(join(contents, "Info.plist"), infoPlist());
  const exe = join(contents, "MacOS", "selfguard");
  atomicWrite(exe, launcherScript(process.execPath, cliEntry()));
  chmodSync(exe, 0o755);
  if (existsSync(iconSource())) copyFileSync(iconSource(), join(contents, "Resources", "selfguard.icns"));
  for (const dir of [path, contents, join(contents, "MacOS"), join(contents, "Resources")]) chmodSync(dir, 0o755);
  chmodSync(join(contents, "Info.plist"), 0o644);
  return appStatus();
}

export function uninstallApp(): boolean {
  assertMac();
  const existed = existsSync(appPath());
  rmSync(appPath(), { recursive: true, force: true });
  return existed;
}
